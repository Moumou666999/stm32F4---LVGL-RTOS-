static SemaphoreHandle_t print_mutex = NULL;

int printf_uart(const char *fmt, ...)
{
  static char buffer[256];
  va_list args;
  int len;

  if (print_mutex == NULL)
  {
    print_mutex = xSemaphoreCreateMutex();
  }
  if (xSemaphoreTake(print_mutex, portMAX_DELAY) != pdTRUE)
    return 0;

  va_start(args, fmt);
  len = vsnprintf(buffer, sizeof(buffer), fmt, args);
  va_end(args);

  if (len > 0)
  {
    HAL_UART_Transmit(&huart1, (uint8_t *)buffer, len, 100);
  }
  xSemaphoreGive(print_mutex);
  return len;
}

#define ESP_RX_BUF_SIZE 512
static uint8_t esp_rx_dma_buf[ESP_RX_BUF_SIZE];
static uint8_t esp_rx_user_buf[ESP_RX_BUF_SIZE];
static volatile uint16_t esp_rx_len = 0;
// TaskHandle_t esp_task_handle = NULL;

#define DEBUG_RX_BUF_SIZE 256
static uint8_t debug_rx_dma_buf[DEBUG_RX_BUF_SIZE];
static uint8_t debug_rx_user_buf[DEBUG_RX_BUF_SIZE];
static volatile uint16_t debug_rx_len = 0;
// TaskHandle_t debug_task_handle = NULL;

void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
  if (huart->Instance == USART2)
  {
    // HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
    if (Size > ESP_RX_BUF_SIZE)
    {
      Size = ESP_RX_BUF_SIZE;
    }
    memcpy(esp_rx_user_buf, esp_rx_dma_buf, Size);
    esp_rx_len = Size;

    BaseType_t xWoken = pdFALSE;
    if (esp_task_handle != NULL)
    {
      vTaskNotifyGiveFromISR(esp_task_handle, &xWoken);
      portYIELD_FROM_ISR(xWoken);
    }

    HAL_UARTEx_ReceiveToIdle_DMA(huart, esp_rx_dma_buf, ESP_RX_BUF_SIZE);
  }
}

void ESP_UART_Init(void)
{
  HAL_UARTEx_ReceiveToIdle_DMA(&huart2, esp_rx_dma_buf, ESP_RX_BUF_SIZE);
  __HAL_DMA_DISABLE_IT(&hdma_usart2_rx, DMA_IT_HT);
}

void DEBUG_UART_Init(void)
{
  HAL_UARTEx_ReceiveToIdle_DMA(&huart1, debug_rx_dma_buf, DEBUG_RX_BUF_SIZE);
  __HAL_DMA_DISABLE_IT(&hdma_usart1_rx, DMA_IT_HT);
}

uint16_t ESP_Uart_Read(uint8_t *buf, uint16_t buf_size)
{
  uint16_t len = esp_rx_len;
  if (len > buf_size)
  {
    len = buf_size;
  }
  memcpy(buf, esp_rx_user_buf, len);
  esp_rx_len = 0;
  return len;
}

